#!/usr/bin/env python3
"""Generate the Masterkey's (MW2's underbarrel shotgun) game data and clip table.

Stdlib only. assets/source/masterkey/weapon.json is the authoring source, and
holds MW2's own weapon data (m4_shotgun_attach_mp and m4_shotgun_mp's alt
fields). Writes:

  code/game/bg_masterkey_data.h                      gameplay timings (MK_*)
  assets/baseq3/models/weapons2/masterkey/view.cfg   the clip table a model plugs into

Clip lengths ARE the gameplay timers: each clip's frame count and rate are
chosen so it lasts exactly its timer's milliseconds at model_fps. A model
exported with these frame ranges plays in step with pmove; one with its own
ranges keeps the same clip names and lengths and edits view.cfg's first two
numbers. --check never writes and fails if a generated file is stale.
"""
import argparse
import json
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'assets/source/masterkey/weapon.json'
HEADER = ROOT / 'code/game/bg_masterkey_data.h'
CLIPS = ROOT / 'assets/baseq3/models/weapons2/masterkey/view.cfg'

# Clip order in the export. Names are cgame's (CG_WeapAnim_RegisterClips).
CLIP_ORDER = [
    ('idle', 'idle_ms', True),
    ('raise', 'raise_ms', False),
    ('drop', 'drop_ms', False),
    ('alt_raise', 'alt_raise_ms', False),
    ('fire', None, False),            # the shot and the pump: fire_ms + rechamber_ms
    ('reload_start', 'reload_start_ms', False),
    ('reload_loop', 'reload_loop_ms', False),
    ('reload_end', 'reload_end_ms', False),
    ('sprint_in', 'sprint_in_ms', False),
    ('sprint_loop', 'sprint_loop_ms', True),
    ('sprint_out', 'sprint_out_ms', False),
]


def fail(message):
    sys.exit('build_masterkey: ' + message)


def load():
    data = json.loads(SOURCE.read_text())
    for key in ('clip_size', 'start_reserve', 'max_reserve', 'pellets', 'fire_ms', 'rechamber_ms',
                'reload_start_ms', 'reload_loop_ms', 'reload_end_ms', 'raise_ms', 'drop_ms',
                'alt_raise_ms', 'host_alt_raise_ms', 'quick_raise_ms', 'quick_drop_ms',
                'sprint_in_ms', 'sprint_out_ms', 'model_fps'):
        if not isinstance(data.get(key), int) or data[key] <= 0:
            fail('%s must be a positive whole number' % key)
    for mode in ('hip', 'ads'):
        for part in ('pitch_min', 'pitch_max', 'yaw_min', 'yaw_max', 'center_speed'):
            if not isinstance(data.get('%s_view_kick_%s' % (mode, part)), int):
                fail('%s_view_kick_%s must be a whole number (MW2 degrees per second)' % (mode, part))
    if data.get('alt_drop_ms') != 0:
        # Every alt pairing in MW2's data drops in 0: an alt switch puts nothing
        # down, and pmove has no alt drop to time.
        fail('alt_drop_ms must be 0 (MW2: an alt switch puts nothing down)')
    if not 0 < data['reload_start_add_ms'] < data['reload_start_ms']:
        fail('reload_start_add_ms must fall inside the reload start')
    if not 0 < data['reload_add_ms'] < data['reload_loop_ms']:
        fail('reload_add_ms must fall inside the reload loop')
    if not 0 < data['reload_end_close_ms'] < data['reload_end_ms']:
        fail('reload_end_close_ms must fall inside the reload end')
    if data['start_reserve'] > data['max_reserve'] or data['clip_size'] > 15 or data['max_reserve'] > 63:
        fail('ammo does not fit the slot fields (clip 4 bits, reserve 6 bits)')
    return data


def c_float(value):
    text = repr(float(value))
    return text + 'f'


def bolt_close(data):
    # MW2's rechamber (575bd8-575c03): weaponDelay is rechamberBoltTime when
    # it is set and shorter than rechamberTime, otherwise 1 ms. The shell is
    # chambered when that delay runs out, counted from the pump's start.
    bolt = data['rechamber_bolt_ms']
    if not (0 < bolt < data['rechamber_ms']):
        bolt = 1
    return data['fire_ms'] + bolt


def header(data):
    lines = [
        '// Generated by dev/tools/build_masterkey.py; edit assets/source/masterkey/weapon.json.',
        '// MW2\'s underbarrel shotgun: ' + data['mw2_alt_weapon'] + ', the alt of ' + data['mw2_host_weapon'] + '.',
        '#ifndef BG_MASTERKEY_DATA_H',
        '#define BG_MASTERKEY_DATA_H',
    ]
    defs = [
        ('MK_MAG_SIZE', data['clip_size']),
        ('MK_START_RESERVE', data['start_reserve']),
        ('MK_MAX_RESERVE', data['max_reserve']),
        ('MK_PELLETS', data['pellets']),
        ('MK_DAMAGE', data['damage']),
        ('MK_MIN_DAMAGE', data['min_damage']),
        ('MK_MAX_DAMAGE_RANGE', data['max_damage_range']),
        ('MK_MIN_DAMAGE_RANGE', data['min_damage_range']),
        # Peace's spread unit: a bullet lands at most spread * 16 off at
        # BG_BULLET_RANGE (8192 * 16), so spread is tan(half angle) * 8192.
        ('MK_HIP_SPREAD', round(math.tan(math.radians(data['hip_spread_deg'])) * 8192)),
        ('MK_ADS_SPREAD_SCALE', c_float(round(data['ads_spread_deg'] / data['hip_spread_deg'], 6))),
        ('MK_FIRE_MS', data['fire_ms'] + data['rechamber_ms']),
        ('MK_BOLT_OPEN_MS', data['fire_ms']),
        ('MK_BOLT_CLOSE_MS', bolt_close(data)),
        ('MK_RELOAD_START_MS', data['reload_start_ms']),
        ('MK_RELOAD_START_ADD_MS', data['reload_start_add_ms']),
        ('MK_RELOAD_LOOP_MS', data['reload_loop_ms']),
        ('MK_ROUND_IN_MS', data['reload_add_ms']),
        ('MK_RELOAD_END_MS', data['reload_end_ms']),
        ('MK_RELOAD_CLOSE_MS', data['reload_end_close_ms']),
        ('MK_RAISE_MS', data['raise_ms']),
        ('MK_DROP_MS', data['drop_ms']),
        ('MK_ALT_RAISE_MS', data['alt_raise_ms']),
        ('MK_HOST_ALT_RAISE_MS', data['host_alt_raise_ms']),
        ('MK_QUICK_RAISE_MS', data['quick_raise_ms']),
        ('MK_QUICK_DROP_MS', data['quick_drop_ms']),
        ('MK_SPRINT_IN_MS', data['sprint_in_ms']),
        ('MK_SPRINT_LOOP_MS', data['sprint_loop_ms']),
        ('MK_SPRINT_OUT_MS', data['sprint_out_ms']),
        ('MK_ADS_IN_MS', data['ads_in_ms']),
        ('MK_ADS_OUT_MS', data['ads_out_ms']),
        ('MK_ADS_ZOOM_FOV', data['ads_zoom_fov']),
    ]
    # MW2's view kick (hip/adsViewKick*), bg_viewKick's row for the underbarrel.
    for mode in ('hip', 'ads'):
        for part in ('pitch_min', 'pitch_max', 'yaw_min', 'yaw_max', 'center_speed'):
            key = '%s_view_kick_%s' % (mode, part)
            defs.append(('MK_' + key.upper(), data[key]))
    lines += ['#define %s %s' % (name, value) for name, value in defs]
    lines += ['#endif', '']
    return '\n'.join(lines)


def clip_table(data):
    fps = data['model_fps']
    first = 0
    lines = ['// Generated from assets/source/masterkey/weapon.json: name firstFrame numFrames fps loop.',
             '// Each clip lasts exactly its gameplay timer. Keep the names and lengths; frame',
             '// starts may move to match an export.']
    for name, key, loop in CLIP_ORDER:
        ms = data['fire_ms'] + data['rechamber_ms'] if key is None else data[key]
        frames = max(1, round(ms * fps / 1000.0))
        rate = frames * 1000.0 / ms
        lines.append('%s %d %d %s %d' % (name, first, frames, ('%.6f' % rate).rstrip('0').rstrip('.'), 1 if loop else 0))
        first += frames
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = load()
    outputs = {HEADER: header(data), CLIPS: clip_table(data)}
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if args.check:
        if stale:
            fail('stale: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale))
        print('build_masterkey: up to date')
        return
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path])
        print('wrote', path.relative_to(ROOT))


if __name__ == '__main__':
    main()
