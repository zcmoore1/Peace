#!/usr/bin/env python3
"""Original, deliberately simple objective case. Deterministic MD3, no textures.

The object is a game prop, not a model of real explosive components.
"""
import argparse
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]


def build():
    surfaces = []
    for name, material, boxes in [
        ("case", "peace/snd_case", [((-10,-7,0),(10,7,5))]),
        ("trim", "peace/snd_trim", [((-10,-7,4),(10,7,5)),
             ((-4,7,1),(-3,10,3)), ((3,7,1),(4,10,3)), ((-4,9,1),(4,10,3))]),
        ("display", "peace/snd_display", [((-4,-3,5),(4,2,5.2))])
    ]:
        vertices, triangles = [], []
        for (x,y,z), (X,Y,Z) in boxes:
            points = [(x,y,z),(X,y,z),(X,Y,z),(x,Y,z),
                      (x,y,Z),(X,y,Z),(X,Y,Z),(x,Y,Z)]
            for face, normal in [((0,3,2,1),(0,0,-1)), ((4,5,6,7),(0,0,1)),
                                 ((0,1,5,4),(0,-1,0)), ((1,2,6,5),(1,0,0)),
                                 ((2,3,7,6),(0,1,0)), ((3,0,4,7),(-1,0,0))]:
                first = len(vertices)
                vertices.extend((points[p],normal) for p in face)
                # Clockwise outward order for Quake's front-face culling.
                triangles.extend(((first,first+2,first+1),(first,first+3,first+2)))
        st = 108 + len(triangles)*12 + 68
        xyz = st + len(vertices)*8
        size = xyz + len(vertices)*8
        blob = bytearray(struct.pack("<4s64s10i", b"IDP3", name.encode(),
            0,1,1,len(vertices),len(triangles),108,108+len(triangles)*12,st,xyz,size))
        blob.extend(b"".join(struct.pack("<3i",*t) for t in triangles))
        blob.extend(struct.pack("<64si",material.encode(),0))
        blob.extend(b"".join(struct.pack("<2f",i%4 in (1,2),i%4 >= 2) for i in range(len(vertices))))
        for point, normal in vertices:
            polar = round(math.acos(normal[2])*255/(2*math.pi)) & 255
            azimuth = round(math.atan2(normal[1],normal[0])*255/(2*math.pi)) & 255
            blob.extend(struct.pack("<3hH",*(round(p*64) for p in point), (azimuth<<8)|polar))
        assert len(blob) == size
        surfaces.append(blob)
    size = 164 + sum(map(len,surfaces))
    model = struct.pack("<4si64s9i",b"IDP3",15,b"Peace objective case",
                        0,1,0,len(surfaces),0,108,164,164,size)
    model += struct.pack("<10f16s",-10,-7,0,10,10,6,0,0,0,16,b"idle")
    model += b"".join(surfaces)
    shader = "// Generated by dev/tools/build_snd_assets.py.\n"
    for name, color in [("case", ".10 .12 .14"), ("trim", ".68 .52 .16"), ("display", ".15 .85 .45")]:
        shader += f"peace/snd_{name}\n{{\n    {{\n        map $whiteimage\n        rgbGen const ( {color} )\n    }}\n}}\n"
    return {ROOT/"assets/baseq3/models/peace/snd_bomb.md3": model,
            ROOT/"assets/baseq3/scripts/peace_snd.shader": shader.encode()}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    for path, data in build().items():
        if check:
            assert path.read_bytes() == data, f"Stale objective asset: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f"{'Checked' if check else 'Built'} {path.relative_to(ROOT)} ({len(data)} bytes)")
